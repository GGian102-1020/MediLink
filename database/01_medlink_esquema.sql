-- 1. TIPOS ENUMERADOS
CREATE TYPE rol_cuenta AS ENUM ('USUARIO', 'OPERADOR', 'ADMINISTRADOR');
CREATE TYPE estado_cuenta AS ENUM ('ACTIVA', 'DESHABILITADA');
CREATE TYPE estado_farmacia AS ENUM ('ACTIVA', 'INACTIVA');
CREATE TYPE estado_medicamento AS ENUM ('ACTIVO', 'INACTIVO');
CREATE TYPE estado_presentacion AS ENUM ('ACTIVA', 'INACTIVA');
CREATE TYPE condicion_dispensa AS ENUM ('VENTA_LIBRE', 'BAJO_RECETA');
CREATE TYPE estado_prescripcion AS ENUM ('ACTIVA', 'ANULADA');
CREATE TYPE estado_reserva AS ENUM ('ACTIVA', 'COMPLETADA', 'CANCELADA', 'VENCIDA');
CREATE TYPE actor_sistema AS ENUM ('USUARIO', 'OPERADOR', 'ADMINISTRADOR', 'SISTEMA');
CREATE TYPE origen_cancelacion AS ENUM ('USUARIO', 'OPERADOR', 'ADMINISTRADOR', 'SISTEMA');
CREATE TYPE causa_cancelacion AS ENUM (
    'CANCELACION_USUARIO', 'STOCK_INCONSISTENTE',
    'PRODUCTO_NO_DISPONIBLE', 'PRODUCTO_NO_APTO_PARA_ENTREGA',
    'IMPEDIMENTO_OPERATIVO_FARMACIA', 'ERROR_ADMINISTRATIVO',
    'CUENTA_DESHABILITADA', 'OTRA_CAUSA'
);
CREATE TYPE tipo_movimiento_stock AS ENUM (
    'RESERVA_CONFIRMADA', 'CANCELACION_RESTITUCION', 'VENCIMIENTO',
    'AJUSTE_MANUAL', 'CORRECCION_STOCK_INCONSISTENTE'
);
CREATE TYPE motivo_suspension AS ENUM ('INCUMPLIMIENTOS_REITERADOS');
CREATE TYPE tipo_entidad_auditoria AS ENUM (
    'CUENTA', 'FARMACIA', 'MEDICAMENTO', 'PRESENTACION', 'STOCK',
    'RESERVA', 'PRESCRIPCION', 'OPERADOR', 'SUSPENSION'
);
CREATE TYPE accion_auditoria AS ENUM (
    'AJUSTAR_STOCK', 'CORREGIR_STOCK_INCONSISTENTE',
    'CANCELAR_RESERVA_OPERATIVA', 'CONFIRMAR_RETIRO',
    'CREAR_FARMACIA', 'EDITAR_FARMACIA', 'DESACTIVAR_FARMACIA',
    'REACTIVAR_FARMACIA', 'CREAR_MEDICAMENTO', 'EDITAR_MEDICAMENTO',
    'DESACTIVAR_MEDICAMENTO', 'REACTIVAR_MEDICAMENTO',
    'CREAR_PRESENTACION', 'DESACTIVAR_PRESENTACION',
    'REACTIVAR_PRESENTACION', 'CREAR_OPERADOR', 'EDITAR_OPERADOR',
    'DESHABILITAR_CUENTA', 'REACTIVAR_CUENTA',
    'CREAR_PRESCRIPCION', 'ANULAR_PRESCRIPCION',
    'CAMBIAR_CONTRASENA', 'CREAR_SUSPENSION'
);

-- 2. CUENTAS Y PERFILES
CREATE TABLE cuenta (
    id_cuenta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    correo VARCHAR(254) NOT NULL,
    -- Se calcula en la BD: mapear como solo lectura en Hibernate/JPA.
    correo_normalizado VARCHAR(254)
        GENERATED ALWAYS AS (lower(btrim(correo))) STORED UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    rol rol_cuenta NOT NULL,
    estado estado_cuenta NOT NULL DEFAULT 'ACTIVA',
    token_version BIGINT NOT NULL DEFAULT 0,
    fecha_hora_creacion TIMESTAMPTZ(3) NOT NULL,
    CONSTRAINT ck_cuenta_correo CHECK (
        length(btrim(correo)) BETWEEN 1 AND 254 AND correo = btrim(correo)
    ),
    CONSTRAINT ck_cuenta_password_hash CHECK (length(btrim(password_hash)) > 0),
    CONSTRAINT ck_cuenta_token_version CHECK (token_version >= 0)
);

CREATE TABLE usuario (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cuenta BIGINT NOT NULL UNIQUE REFERENCES cuenta(id_cuenta),
    nombre VARCHAR(80) NOT NULL,
    apellido VARCHAR(80) NOT NULL,
    CONSTRAINT ck_usuario_nombre CHECK (length(btrim(nombre)) BETWEEN 1 AND 80),
    CONSTRAINT ck_usuario_apellido CHECK (length(btrim(apellido)) BETWEEN 1 AND 80)
);

CREATE TABLE farmacia (
    id_farmacia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    direccion VARCHAR(200) NOT NULL,
    telefono VARCHAR(30),
    email_contacto VARCHAR(254),
    estado estado_farmacia NOT NULL DEFAULT 'ACTIVA',
    CONSTRAINT ck_farmacia_nombre CHECK (length(btrim(nombre)) BETWEEN 1 AND 120),
    CONSTRAINT ck_farmacia_direccion CHECK (length(btrim(direccion)) BETWEEN 1 AND 200),
    CONSTRAINT ck_farmacia_telefono CHECK (
        telefono IS NULL OR length(btrim(telefono)) BETWEEN 1 AND 30
    ),
    CONSTRAINT ck_farmacia_contacto CHECK (
        email_contacto IS NULL OR length(btrim(email_contacto)) BETWEEN 1 AND 254
    )
);

CREATE TABLE operador (
    id_operador BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cuenta BIGINT NOT NULL UNIQUE REFERENCES cuenta(id_cuenta),
    id_farmacia BIGINT NOT NULL REFERENCES farmacia(id_farmacia),
    nombre VARCHAR(80) NOT NULL,
    apellido VARCHAR(80) NOT NULL,
    CONSTRAINT ck_operador_nombre CHECK (length(btrim(nombre)) BETWEEN 1 AND 80),
    CONSTRAINT ck_operador_apellido CHECK (length(btrim(apellido)) BETWEEN 1 AND 80)
);

CREATE TABLE administrador (
    id_administrador BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cuenta BIGINT NOT NULL UNIQUE REFERENCES cuenta(id_cuenta),
    nombre VARCHAR(80) NOT NULL,
    apellido VARCHAR(80) NOT NULL,
    CONSTRAINT ck_administrador_nombre CHECK (length(btrim(nombre)) BETWEEN 1 AND 80),
    CONSTRAINT ck_administrador_apellido CHECK (length(btrim(apellido)) BETWEEN 1 AND 80)
);

-- 3. CATALOGO Y STOCK
CREATE TABLE medicamento (
    id_medicamento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(160) NOT NULL,
    estado estado_medicamento NOT NULL DEFAULT 'ACTIVO',
    CONSTRAINT ck_medicamento_nombre CHECK (length(btrim(nombre)) BETWEEN 1 AND 160)
    -- El nombre NO es UNIQUE (RN-09).
);

CREATE TABLE presentacion_medicamento (
    id_presentacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_medicamento BIGINT NOT NULL REFERENCES medicamento(id_medicamento),
    concentracion_texto VARCHAR(80) NOT NULL,
    forma_farmaceutica VARCHAR(80) NOT NULL,
    cantidad_envase INTEGER NOT NULL,
    unidad_expendio VARCHAR(80) NOT NULL,
    condicion_dispensa condicion_dispensa NOT NULL,
    estado estado_presentacion NOT NULL DEFAULT 'ACTIVA',
    CONSTRAINT ck_presentacion_cantidad_envase CHECK (cantidad_envase > 0),
    CONSTRAINT ck_presentacion_concentracion CHECK (
        length(btrim(concentracion_texto)) BETWEEN 1 AND 80
        AND concentracion_texto = regexp_replace(btrim(concentracion_texto), '[[:space:]]+', ' ', 'g')
    ),
    CONSTRAINT ck_presentacion_forma CHECK (
        length(btrim(forma_farmaceutica)) BETWEEN 1 AND 80
        AND forma_farmaceutica = regexp_replace(btrim(forma_farmaceutica), '[[:space:]]+', ' ', 'g')
    ),
    CONSTRAINT ck_presentacion_unidad CHECK (
        length(btrim(unidad_expendio)) BETWEEN 1 AND 80
        AND unidad_expendio = regexp_replace(btrim(unidad_expendio), '[[:space:]]+', ' ', 'g')
    )
);

-- Identidad estructural ACTIVA, sin conversion farmacologica entre unidades.
CREATE UNIQUE INDEX ux_presentacion_activa_identidad
    ON presentacion_medicamento (
        id_medicamento,
        lower(concentracion_texto),
        lower(forma_farmaceutica),
        cantidad_envase,
        lower(unidad_expendio),
        condicion_dispensa
    ) WHERE estado = 'ACTIVA';

CREATE TABLE stock (
    id_stock BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_farmacia BIGINT NOT NULL REFERENCES farmacia(id_farmacia),
    id_presentacion BIGINT NOT NULL REFERENCES presentacion_medicamento(id_presentacion),
    cantidad_disponible INTEGER NOT NULL DEFAULT 0,
    fecha_hora_actualizacion TIMESTAMPTZ(3) NOT NULL,
    CONSTRAINT uq_stock_farmacia_presentacion UNIQUE (id_farmacia, id_presentacion),
    CONSTRAINT ck_stock_no_negativo CHECK (cantidad_disponible >= 0)
);

-- 4. PRESCRIPCIONES
CREATE TABLE prescripcion (
    id_prescripcion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_externo VARCHAR(80) NOT NULL UNIQUE,
    id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario),
    fecha_emision DATE NOT NULL,
    fecha_vencimiento DATE NOT NULL,
    estado estado_prescripcion NOT NULL DEFAULT 'ACTIVA',
    fecha_hora_creacion TIMESTAMPTZ(3) NOT NULL,
    CONSTRAINT ck_prescripcion_codigo CHECK (length(btrim(codigo_externo)) BETWEEN 1 AND 80),
    CONSTRAINT ck_prescripcion_fechas CHECK (fecha_emision <= fecha_vencimiento)
);

CREATE TABLE item_prescripcion (
    id_item_prescripcion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_prescripcion BIGINT NOT NULL REFERENCES prescripcion(id_prescripcion),
    id_presentacion BIGINT NOT NULL REFERENCES presentacion_medicamento(id_presentacion),
    cantidad_autorizada INTEGER NOT NULL,
    cantidad_comprometida INTEGER NOT NULL DEFAULT 0,
    cantidad_utilizada INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT uq_item_prescripcion_presentacion UNIQUE (id_prescripcion, id_presentacion),
    CONSTRAINT ck_item_cantidades CHECK (
        cantidad_autorizada > 0
        AND cantidad_comprometida >= 0
        AND cantidad_utilizada >= 0
        AND cantidad_comprometida::BIGINT + cantidad_utilizada::BIGINT
            <= cantidad_autorizada::BIGINT
    )
);

-- 5. RESERVAS
CREATE TABLE reserva (
    id_reserva BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_visible VARCHAR(12) NOT NULL UNIQUE,
    id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario),
    id_farmacia BIGINT NOT NULL REFERENCES farmacia(id_farmacia),
    id_presentacion BIGINT NOT NULL REFERENCES presentacion_medicamento(id_presentacion),
    id_item_prescripcion BIGINT REFERENCES item_prescripcion(id_item_prescripcion),
    cantidad INTEGER NOT NULL,
    estado_persistido estado_reserva NOT NULL DEFAULT 'ACTIVA',
    fecha_hora_creacion TIMESTAMPTZ(3) NOT NULL,
    fecha_hora_vencimiento TIMESTAMPTZ(3) NOT NULL,
    fecha_hora_cancelacion TIMESTAMPTZ(3),
    fecha_hora_retiro TIMESTAMPTZ(3),
    origen_cancelacion origen_cancelacion,
    causa_cancelacion causa_cancelacion,
    motivo_cancelacion VARCHAR(500),
    farmacia_nombre_snapshot VARCHAR(120) NOT NULL,
    farmacia_direccion_snapshot VARCHAR(200) NOT NULL,
    medicamento_nombre_snapshot VARCHAR(160) NOT NULL,
    presentacion_descripcion_snapshot TEXT NOT NULL,
    CONSTRAINT ck_reserva_cantidad CHECK (cantidad > 0),
    -- El codigo se almacena canonico EN MAYUSCULAS; busquedas: upper(:codigo).
    CONSTRAINT ck_reserva_codigo CHECK (
        codigo_visible COLLATE "C" ~ '^[0-9A-HJKMNP-TV-Z]{12}$'
    ),
    -- Configuracion fija del MVP: DURACION_RESERVA = 4 horas.
    CONSTRAINT ck_reserva_duracion CHECK (
        fecha_hora_vencimiento = fecha_hora_creacion + INTERVAL '4 hours'
    ),
    CONSTRAINT ck_reserva_snapshots CHECK (
        length(btrim(farmacia_nombre_snapshot)) > 0
        AND length(btrim(farmacia_direccion_snapshot)) > 0
        AND length(btrim(medicamento_nombre_snapshot)) > 0
        AND length(btrim(presentacion_descripcion_snapshot)) > 0
    ),
    CONSTRAINT ck_reserva_metadatos_estado CHECK (
        (estado_persistido IN ('ACTIVA', 'VENCIDA')
            AND fecha_hora_cancelacion IS NULL AND fecha_hora_retiro IS NULL
            AND origen_cancelacion IS NULL AND causa_cancelacion IS NULL
            AND motivo_cancelacion IS NULL)
        OR (estado_persistido = 'COMPLETADA'
            AND fecha_hora_retiro IS NOT NULL
            AND fecha_hora_retiro >= fecha_hora_creacion
            AND fecha_hora_retiro < fecha_hora_vencimiento
            AND fecha_hora_cancelacion IS NULL
            AND origen_cancelacion IS NULL AND causa_cancelacion IS NULL
            AND motivo_cancelacion IS NULL)
        OR (estado_persistido = 'CANCELADA'
            AND fecha_hora_cancelacion IS NOT NULL
            AND fecha_hora_cancelacion >= fecha_hora_creacion
            AND fecha_hora_cancelacion < fecha_hora_vencimiento
            AND fecha_hora_retiro IS NULL
            AND origen_cancelacion IS NOT NULL
            AND causa_cancelacion IS NOT NULL)
    ),
    CONSTRAINT ck_reserva_causa_origen CHECK (
        estado_persistido <> 'CANCELADA' OR (
            (causa_cancelacion = 'CANCELACION_USUARIO' AND origen_cancelacion = 'USUARIO')
            OR (causa_cancelacion = 'CUENTA_DESHABILITADA' AND origen_cancelacion = 'SISTEMA')
            OR (causa_cancelacion = 'ERROR_ADMINISTRATIVO' AND origen_cancelacion = 'ADMINISTRADOR')
            OR (causa_cancelacion IN (
                'STOCK_INCONSISTENTE', 'PRODUCTO_NO_DISPONIBLE',
                'PRODUCTO_NO_APTO_PARA_ENTREGA', 'IMPEDIMENTO_OPERATIVO_FARMACIA',
                'OTRA_CAUSA'
            ) AND origen_cancelacion IN ('OPERADOR', 'ADMINISTRADOR'))
        )
    ),
    CONSTRAINT ck_reserva_motivo_causa CHECK (
        estado_persistido <> 'CANCELADA'
        OR causa_cancelacion NOT IN (
            'PRODUCTO_NO_DISPONIBLE', 'PRODUCTO_NO_APTO_PARA_ENTREGA',
            'IMPEDIMENTO_OPERATIVO_FARMACIA', 'ERROR_ADMINISTRATIVO', 'OTRA_CAUSA'
        )
        OR coalesce(length(btrim(motivo_cancelacion)), 0) BETWEEN 1 AND 500
    )
);

-- 6. SUSPENSIONES
CREATE TABLE suspension (
    id_suspension BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario),
    fecha_hora_inicio TIMESTAMPTZ(3) NOT NULL,
    fecha_hora_fin TIMESTAMPTZ(3) NOT NULL,
    motivo motivo_suspension NOT NULL DEFAULT 'INCUMPLIMIENTOS_REITERADOS',
    CONSTRAINT ck_suspension_fechas CHECK (fecha_hora_fin > fecha_hora_inicio),
    -- Duracion normativa: 7 dias EXACTOS (168 horas).
    CONSTRAINT ck_suspension_duracion CHECK (
        fecha_hora_fin = fecha_hora_inicio + INTERVAL '168 hours'
    ),
    CONSTRAINT ex_suspension_sin_superposicion EXCLUDE USING gist (
        id_usuario WITH =,
        tstzrange(fecha_hora_inicio, fecha_hora_fin, '[)') WITH &&
    )
);

-- 7. MOVIMIENTOS Y AUDITORIA
CREATE TABLE movimiento_stock (
    id_movimiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_stock BIGINT NOT NULL REFERENCES stock(id_stock),
    id_reserva BIGINT REFERENCES reserva(id_reserva),
    tipo tipo_movimiento_stock NOT NULL,
    cantidad_anterior INTEGER NOT NULL,
    cantidad_nueva INTEGER NOT NULL,
    delta INTEGER NOT NULL,
    fecha_hora TIMESTAMPTZ(3) NOT NULL,
    actor_cuenta_id BIGINT REFERENCES cuenta(id_cuenta),
    motivo VARCHAR(500),
    CONSTRAINT ck_movimiento_saldos CHECK (
        cantidad_anterior >= 0
        AND cantidad_nueva >= 0
        AND delta::BIGINT = cantidad_nueva::BIGINT - cantidad_anterior::BIGINT
