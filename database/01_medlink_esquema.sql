    -- RN-04: el ajuste manual siempre exige motivo.
    CONSTRAINT ck_movimiento_ajuste_motivo CHECK (
        tipo <> 'AJUSTE_MANUAL' OR
        coalesce(length(btrim(motivo)), 0) BETWEEN 1 AND 500
    )
);

