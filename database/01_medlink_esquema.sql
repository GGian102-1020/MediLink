    ] LOOP
        EXECUTE format(
            'CREATE TRIGGER %I BEFORE DELETE ON %I FOR EACH ROW EXECUTE FUNCTION medlink_no_borrar()',
            'trg_' || v_tabla || '_no_delete', v_tabla
        );
    END LOOP;
END;
$$;

