-- 10. INTEGRIDAD CUENTA-PERFIL (DIFERIDA HASTA COMMIT)
-- Crear Cuenta + perfil correspondiente en la MISMA transaccion.
CREATE FUNCTION medlink_validar_cuenta_perfil() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
    v_id BIGINT;
    v_rol rol_cuenta;
    v_usuarios INTEGER;
    v_operadores INTEGER;
    v_administradores INTEGER;
BEGIN
    v_id := NEW.id_cuenta;

    SELECT rol INTO v_rol FROM cuenta WHERE id_cuenta = v_id;
    IF NOT FOUND THEN
        RETURN NEW;
    END IF;

    SELECT count(*) INTO v_usuarios FROM usuario WHERE id_cuenta = v_id;
    SELECT count(*) INTO v_operadores FROM operador WHERE id_cuenta = v_id;
    SELECT count(*) INTO v_administradores FROM administrador WHERE id_cuenta = v_id;

    IF v_usuarios + v_operadores + v_administradores <> 1
        OR (v_rol = 'USUARIO' AND v_usuarios <> 1)
        OR (v_rol = 'OPERADOR' AND v_operadores <> 1)
        OR (v_rol = 'ADMINISTRADOR' AND v_administradores <> 1) THEN
        RAISE EXCEPTION 'La cuenta % debe tener exactamente el perfil de su rol (%)', v_id, v_rol;
    END IF;
    RETURN NEW;
END;
$$;

-- Serializa inserciones de perfiles de tipos distintos sobre la misma Cuenta.
CREATE FUNCTION medlink_bloquear_cuenta_para_perfil() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    PERFORM 1 FROM cuenta WHERE id_cuenta = NEW.id_cuenta FOR UPDATE;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_usuario_lock_cuenta BEFORE INSERT ON usuario
    FOR EACH ROW EXECUTE FUNCTION medlink_bloquear_cuenta_para_perfil();
CREATE TRIGGER trg_operador_lock_cuenta BEFORE INSERT ON operador
    FOR EACH ROW EXECUTE FUNCTION medlink_bloquear_cuenta_para_perfil();
CREATE TRIGGER trg_admin_lock_cuenta BEFORE INSERT ON administrador
    FOR EACH ROW EXECUTE FUNCTION medlink_bloquear_cuenta_para_perfil();

CREATE CONSTRAINT TRIGGER trg_cuenta_validar_perfil
    AFTER INSERT OR UPDATE ON cuenta DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION medlink_validar_cuenta_perfil();
CREATE CONSTRAINT TRIGGER trg_usuario_validar_perfil
    AFTER INSERT OR UPDATE ON usuario DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION medlink_validar_cuenta_perfil();
CREATE CONSTRAINT TRIGGER trg_operador_validar_perfil
    AFTER INSERT OR UPDATE ON operador DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION medlink_validar_cuenta_perfil();
CREATE CONSTRAINT TRIGGER trg_admin_validar_perfil
    AFTER INSERT OR UPDATE ON administrador DEFERRABLE INITIALLY DEFERRED
