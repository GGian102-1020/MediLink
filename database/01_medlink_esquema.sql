CREATE FUNCTION medlink_proteger_campos_inmutables() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_TABLE_NAME = 'cuenta' THEN
        IF NEW.rol IS DISTINCT FROM OLD.rol THEN
            RAISE EXCEPTION 'El rol de una Cuenta es inmutable';
        END IF;
    ELSIF TG_TABLE_NAME = 'stock' THEN
        IF (NEW.id_stock, NEW.id_farmacia, NEW.id_presentacion)
           IS DISTINCT FROM
           (OLD.id_stock, OLD.id_farmacia, OLD.id_presentacion) THEN
            RAISE EXCEPTION 'La identidad del Stock (Farmacia/Presentacion) es inmutable';
        END IF;
    ELSIF TG_TABLE_NAME = 'operador' THEN
        IF (NEW.id_cuenta, NEW.id_farmacia) IS DISTINCT FROM
           (OLD.id_cuenta, OLD.id_farmacia) THEN
            RAISE EXCEPTION 'Cuenta y Farmacia del Operador son inmutables';
        END IF;
    ELSIF TG_TABLE_NAME = 'usuario' THEN
        IF NEW.id_cuenta IS DISTINCT FROM OLD.id_cuenta THEN
            RAISE EXCEPTION 'Cuenta del Usuario es inmutable';
        END IF;
    ELSIF TG_TABLE_NAME = 'administrador' THEN
        IF NEW.id_cuenta IS DISTINCT FROM OLD.id_cuenta THEN
            RAISE EXCEPTION 'Cuenta del Administrador es inmutable';
        END IF;
    ELSIF TG_TABLE_NAME = 'presentacion_medicamento' THEN
        IF (NEW.id_medicamento, NEW.concentracion_texto, NEW.forma_farmaceutica,
            NEW.cantidad_envase, NEW.unidad_expendio, NEW.condicion_dispensa)
           IS DISTINCT FROM
           (OLD.id_medicamento, OLD.concentracion_texto, OLD.forma_farmaceutica,
            OLD.cantidad_envase, OLD.unidad_expendio, OLD.condicion_dispensa) THEN
            RAISE EXCEPTION 'Estructura de Presentacion inmutable';
        END IF;
    ELSIF TG_TABLE_NAME = 'prescripcion' THEN
        IF (NEW.codigo_externo, NEW.id_usuario, NEW.fecha_emision,
            NEW.fecha_vencimiento, NEW.fecha_hora_creacion)
           IS DISTINCT FROM
           (OLD.codigo_externo, OLD.id_usuario, OLD.fecha_emision,
            OLD.fecha_vencimiento, OLD.fecha_hora_creacion) THEN
            RAISE EXCEPTION 'Datos estructurales de Prescripcion inmutables';
        END IF;
        IF OLD.estado = 'ANULADA' AND NEW.estado <> 'ANULADA' THEN
            RAISE EXCEPTION 'Prescripcion ANULADA no se puede reactivar';
        END IF;
    ELSIF TG_TABLE_NAME = 'item_prescripcion' THEN
        IF (NEW.id_prescripcion, NEW.id_presentacion, NEW.cantidad_autorizada)
           IS DISTINCT FROM
           (OLD.id_prescripcion, OLD.id_presentacion, OLD.cantidad_autorizada) THEN
            RAISE EXCEPTION 'Estructura de ItemPrescripcion inmutable';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_cuenta_inmutable BEFORE UPDATE ON cuenta
