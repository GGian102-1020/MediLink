-- 11. INTEGRIDAD RESERVA / ITEM DE PRESCRIPCION
-- Comprueba la condicion de dispensa y, para BAJO_RECETA, mismo usuario
-- y presentacion. Una receta anulada DESPUES no invalida la Reserva previa.
CREATE FUNCTION medlink_validar_reserva_rx() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
    v_condicion condicion_dispensa;
BEGIN
    SELECT condicion_dispensa INTO v_condicion
      FROM presentacion_medicamento
     WHERE id_presentacion = NEW.id_presentacion;

    IF v_condicion = 'VENTA_LIBRE' THEN
        IF NEW.id_item_prescripcion IS NOT NULL THEN
            RAISE EXCEPTION 'VENTA_LIBRE requiere id_item_prescripcion NULL';
        END IF;
    ELSIF v_condicion = 'BAJO_RECETA' THEN
        IF NEW.id_item_prescripcion IS NULL OR NOT EXISTS (
            SELECT 1 FROM item_prescripcion i
            JOIN prescripcion p ON p.id_prescripcion = i.id_prescripcion
            WHERE i.id_item_prescripcion = NEW.id_item_prescripcion
              AND i.id_presentacion = NEW.id_presentacion
              AND p.id_usuario = NEW.id_usuario
        ) THEN
            RAISE EXCEPTION 'El item Rx debe pertenecer al usuario y presentacion de la reserva';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_reserva_validar_rx
    BEFORE INSERT OR UPDATE OF id_usuario, id_presentacion, id_item_prescripcion
    ON reserva FOR EACH ROW EXECUTE FUNCTION medlink_validar_reserva_rx();

-- 12. COHERENCIA DEL MOVIMIENTO CON LA RESERVA VINCULADA
CREATE FUNCTION medlink_validar_movimiento_reserva() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
    v_cantidad INTEGER;
BEGIN
    IF NEW.id_reserva IS NULL THEN
        RETURN NEW;
    END IF;

    SELECT r.cantidad INTO v_cantidad
    FROM reserva r
    JOIN stock s ON s.id_stock = NEW.id_stock
    WHERE r.id_reserva = NEW.id_reserva
      AND r.id_farmacia = s.id_farmacia
      AND r.id_presentacion = s.id_presentacion;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Movimiento y Reserva deben corresponder al mismo Stock';
    END IF;

    IF NEW.tipo = 'RESERVA_CONFIRMADA' AND NEW.delta <> -v_cantidad THEN
        RAISE EXCEPTION 'Descuento de reserva incorrecto';
    END IF;
    IF NEW.tipo IN ('CANCELACION_RESTITUCION', 'VENCIMIENTO')
       AND NEW.delta <> v_cantidad THEN
        RAISE EXCEPTION 'Restitucion de reserva incorrecta';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_movimiento_validar_reserva BEFORE INSERT ON movimiento_stock
    FOR EACH ROW EXECUTE FUNCTION medlink_validar_movimiento_reserva();

