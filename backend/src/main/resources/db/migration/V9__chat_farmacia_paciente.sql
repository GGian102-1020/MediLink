-- Chat entre la farmacia (operadores) y un paciente.
-- Una conversación es el par (farmacia, usuario); solo se permite si el paciente tiene
-- al menos una reserva en esa farmacia (regla validada en el backend).
CREATE TABLE mensaje_chat (
    id_mensaje BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_farmacia BIGINT NOT NULL REFERENCES farmacia(id_farmacia),
    id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario),
    -- Quién escribió: la farmacia (un operador) o el paciente.
    autor VARCHAR(10) NOT NULL,
    id_cuenta_autor BIGINT NOT NULL REFERENCES cuenta(id_cuenta),
    texto VARCHAR(1000) NOT NULL,
    fecha_hora TIMESTAMPTZ(3) NOT NULL,
    -- Momento en que el destinatario abrió la conversación; NULL = no leído.
    fecha_hora_lectura TIMESTAMPTZ(3),
    CONSTRAINT ck_mensaje_chat_autor CHECK (autor IN ('FARMACIA', 'USUARIO')),
    CONSTRAINT ck_mensaje_chat_texto CHECK (length(btrim(texto)) BETWEEN 1 AND 1000)
);

CREATE INDEX ix_mensaje_chat_conversacion ON mensaje_chat (id_farmacia, id_usuario, id_mensaje);
CREATE INDEX ix_mensaje_chat_usuario ON mensaje_chat (id_usuario, id_mensaje);
-- No leídos por destinatario (contadores del dashboard y de la app).
CREATE INDEX ix_mensaje_chat_no_leidos ON mensaje_chat (id_farmacia, autor)
    WHERE fecha_hora_lectura IS NULL;
