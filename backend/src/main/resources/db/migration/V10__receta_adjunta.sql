-- Receta (PDF o imagen) que el paciente adjunta al reservar un medicamento BAJO_RECETA.
-- El backend crea con ella una Prescripción propia del paciente (1 ítem: la presentación y
-- cantidad reservadas), de modo que la reserva usa el circuito habitual de compromiso,
-- liberación y consumo. La farmacia consulta el archivo para verificarlo al entregar.
CREATE TABLE receta_adjunta (
    id_receta_adjunta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_prescripcion BIGINT NOT NULL UNIQUE REFERENCES prescripcion(id_prescripcion),
    nombre_archivo VARCHAR(120) NOT NULL,
    content_type VARCHAR(40) NOT NULL,
    tamano_bytes INTEGER NOT NULL,
    contenido BYTEA NOT NULL,
    sha256 CHAR(64) NOT NULL,
    fecha_hora_carga TIMESTAMPTZ(3) NOT NULL,
    CONSTRAINT ck_receta_adjunta_tipo CHECK (
        content_type IN ('application/pdf', 'image/jpeg', 'image/png', 'image/webp')),
    CONSTRAINT ck_receta_adjunta_tamano CHECK (tamano_bytes BETWEEN 1 AND 8388608),
    CONSTRAINT ck_receta_adjunta_nombre CHECK (length(btrim(nombre_archivo)) BETWEEN 1 AND 120)
);
